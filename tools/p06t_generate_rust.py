"""Generate a closed data-only Rust candidate from freshly pinned #717 bytes."""
import argparse
from pathlib import Path
import json
from p06t_shell_catalog import no_links, HERE, ROOT, build, load_sources, canonical, sha, require

VARIANTS = ("Ms1Stock", "Is7Stock", "T26Stock", "T34Stock", "T3485Stock", "WtE100128", "WtE100150", "Fv215b183")
FAMILIES = {"ARMOR_PIERCING": "ArmorPiercing", "ARMOR_PIERCING_CR": "ArmorPiercingCr", "HOLLOW_CHARGE": "HollowCharge", "HIGH_EXPLOSIVE": "HighExplosive"}


def quoted(value):
    return json.dumps(value, ensure_ascii=True)


def number(value):
    return repr(float(value))


def generate(catalog):
    result = ["//! Staged data-only #717 shell catalogue. No runtime registration/admission.",
              "//! Generated by p06t_generate_rust.py after original-file hash verification.",
              "//! Damage/splash/module algorithms and native acceptance remain separate gates.",
              "pub const SOURCE_REVISION:&str=" + quoted(catalog["source_revision"]) + ";",
              "pub const SOURCE_DATA_SHA256:&str=" + quoted(sha(canonical(catalog) + b"\n")) + ";",
              "#[derive(Clone,Copy,Debug,PartialEq,Eq)]\n#[repr(usize)]\npub enum Mount {" + ",".join(VARIANTS) + "}",
              "impl Mount { pub const ALL:[Self;8]=[" + ",".join("Self::" + v for v in VARIANTS) + "];",
              "pub fn index(self)->usize{self as usize}",
              "pub fn from_label(label:&str)->Option<Self>{match label{" + ",".join(quoted(r["id"]) + "=>Some(Self::" + v + ")" for r, v in zip(catalog["mounts"], VARIANTS)) + ",_=>None}}}",
              "#[derive(Clone,Copy,Debug,PartialEq,Eq)]\npub enum Family {ArmorPiercing,ArmorPiercingCr,HollowCharge,HighExplosive}",
              "impl Family {pub fn source_name(self)->&'static str {match self{" + ",".join("Self::" + variant + "=>" + quoted(name) for name, variant in FAMILIES.items()) + "}}}",
              "#[derive(Clone,Copy,Debug,PartialEq)]\npub struct Shell {pub resource:&'static str,pub compact_descr:u16,pub family:Family,pub caliber_mm:f64,pub damage_hp:u16,pub device_damage:u16,pub penetration_mm:[f64;2],pub explosion_radius_m:Option<f64>,pub raw_speed_mps:f64,pub projectile_speed_factor:f64,pub speed_mps:f64,pub raw_gravity_mps2:f64,pub gravity_mps2:f64,pub max_distance_m:f64,pub premium_gold_flag:bool,pub effects_resource:&'static str,pub piercing_power_loss_factor_by_distance:Option<f64>}",
              "#[derive(Clone,Copy,Debug,PartialEq)]\npub struct GunProfile {pub mount:Mount,pub native_nation_id:u8,pub vehicle_type_compact_descr:u16,pub gun_compact_descr:u16,pub capacity:u16,pub reload_seconds:f64,pub clip_count:u8,pub clip_interval_seconds:f64,pub clip_from_mounted_source:bool,pub burst_count:u8,pub burst_interval_seconds:f64,pub additional_vehicle_qualification_required:bool,pub shots:[Shell;3]}",
              "pub const PROFILES:[GunProfile;8]=["]
    for i, profile in enumerate(catalog["mounts"]):
        result.append("GunProfile{mount:Mount::" + VARIANTS[i] + ",native_nation_id:" + str(profile["native_nation_id"]) +
                      ",vehicle_type_compact_descr:" + str(profile["vehicle_type_compact_descr"]) + ",gun_compact_descr:" + str(profile["gun_compact_descr"]) +
                      ",capacity:" + str(profile["max_ammo"]) + ",reload_seconds:" + number(profile["reload_seconds"]) +
                      ",clip_count:" + str(profile["clip_count"]) + ",clip_interval_seconds:" + number(profile["clip_interval_seconds"]) +
                      ",clip_from_mounted_source:" + str(profile["clip_source"] == "MOUNTED").lower() +
                      ",burst_count:1,burst_interval_seconds:0.,additional_vehicle_qualification_required:" + str(i >= 5).lower() + ",shots:[")
        for shell in profile["shots"]:
            optional = lambda name: "None" if shell[name] is None else "Some(" + number(shell[name]) + ")"
            result.append("Shell{resource:" + quoted(shell["resource"]) + ",compact_descr:" + str(shell["compact_descr"]) +
                          ",family:Family::" + FAMILIES[shell["family"]] + ",caliber_mm:" + number(shell["caliber_mm"]) +
                          ",damage_hp:" + str(shell["damage_hp"]) + ",device_damage:" + str(shell["device_damage"]) +
                          ",penetration_mm:[" + ",".join(number(n) for n in shell["penetration_mm"]) + "],explosion_radius_m:" + optional("explosion_radius_m") +
                          ",raw_speed_mps:" + number(shell["raw_speed_mps"]) + ",projectile_speed_factor:" + number(shell["projectile_speed_factor"]) +
                          ",speed_mps:" + number(shell["speed_mps"]) + ",raw_gravity_mps2:" + number(shell["raw_gravity_mps2"]) +
                          ",gravity_mps2:" + number(shell["gravity_mps2"]) + ",max_distance_m:" + number(shell["max_distance_m"]) +
                          ",premium_gold_flag:" + str(shell["premium_gold_flag"]).lower() + ",effects_resource:" + quoted(shell["effects_resource"]) +
                          ",piercing_power_loss_factor_by_distance:" + optional("piercing_power_loss_factor_by_distance") + "},")
        result.append("]},")
    result.extend(["];", "pub fn profile(mount:Mount)->&'static GunProfile{&PROFILES[mount.index()]}",
                   "/// Catalogue membership only. Server inventory, selection, reload and actor\n/// ownership must be checked separately by authority before a shot is admitted.",
                   "pub fn shell(mount:Mount,compact:i32)->Option<&'static Shell>{let id=u16::try_from(compact).ok()?;profile(mount).shots.iter().find(|s|s.compact_descr==id)}",
                   "#[cfg(test)]\n#[path=\"p06t_shell_data_tests.rs\"]\nmod tests;", ""])
    return "\n".join(result).encode("utf-8")


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--original", type=Path, required=True)
    p.add_argument("--out", type=Path, required=True)
    args = p.parse_args()
    out = no_links(args.out).resolve()
    require(out.is_relative_to(ROOT / "local") and not out.exists(), "fresh local candidate required")
    data = generate(build(load_sources(args.original)))
    require(0 < len(data) < 65536, "Rust source size bound")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(data)
    print(json.dumps(dict(status="GENERATED_STAGED_DATA_ONLY", path=str(out), bytes=len(data), sha256=sha(data), runtime_registration=False)))


if __name__ == "__main__":
    main()
