def read_barracks(original_root):
    # Reuse the bounded central-directory admission before ZipFile allocation.
    baseline.read_application(original_root)
    try:
        path = static.no_links(original_root / 'res/packages/gui.pkg')
        with zipfile.ZipFile(path) as archive:
            matches = [item for item in archive.infolist() if item.filename == BARRACKS_MEMBER]
            require(len(matches) == 1, 'unique barracks.swf member required')
            item = matches[0]
            require(item.file_size == BARRACKS_PIN[0] and 0 < item.compress_size <= 2 * 1024 * 1024
                    and item.compress_type in (0, 8) and not item.flag_bits & 1,
                    'bounded unencrypted barracks member required')
            with archive.open(item) as stream:
                raw = stream.read(BARRACKS_PIN[0] + 1)
        require(len(raw) == BARRACKS_PIN[0] and digest(raw) == BARRACKS_PIN[1], 'barracks SWF pin mismatch')
        return raw
    except (OSError, ValueError, zipfile.BadZipFile, RuntimeError) as error:
        raise SourceAuditError('barracks source read failed: ' + str(error)) from error


