"""CAT-01: build the single versioned server catalog and its language bindings.

One tool, two inputs: the pinned read-only #717 client resources (through the
existing bounded readers; no client code is executed) and the authored server
profiles in ``config/catalog/server_profiles.v1.json``. Everything that the
client defines (compact IDs, descriptor, HP, ammunition capacity, crew seats and
roles, ordered shells) is derived from the client and never copied by hand.
Server-only facts are the profile kind, ``battle_admission``, the legacy
inventory binding and the client UI hint flags.

Commands:
  build --original ROOT          rebuild from the client, write catalog + bindings
  verify-source --original ROOT  rebuild from the client, compare with committed
  check                          regenerate bindings from the committed catalog
                                 and compare bytes (no client needed)

The catalog SHA-256 is over the exact bytes of ``catalog.v1.json`` (canonical
JSON + LF). Every binding embeds it; consumers refuse a foreign hash.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
for _path in (str(ROOT), str(ROOT / "tools")):
    if _path not in sys.path:
        sys.path.insert(0, _path)

SCHEMA = "wot091-server-catalog.v1"
PROFILES_SCHEMA = "wot091-server-profiles.v1"
TARGET = "v.0.9.1 #717 RU"
PROFILES_PATH = ROOT / "config/catalog/server_profiles.v1.json"
CATALOG_PATH = ROOT / "config/catalog/catalog.v1.json"
BINDINGS = {
    "rust": ROOT / "server/gateway/src/shared/vehicle_catalog.rs",
    "python": ROOT / "tools/catalog_v1_data.py",
    "js": ROOT / "web/src/catalog-v1.mjs",
    "py27": ROOT / "client_patch/catalog_v1_hints.py",
}
ADMISSION = ("always", "zero_economy_policy", "none")
FAMILY_SUFFIX = {"ARMOR_PIERCING": "ap", "ARMOR_PIERCING_CR": "apcr",
                 "HOLLOW_CHARGE": "heat", "HIGH_EXPLOSIVE": "he"}
MODULE_ROLES = ("chassis", "engine", "fuelTank", "radio", "turret", "gun")
DEVICES = ("engine", "ammoBay", "fuelTank", "radio", "leftTrack", "rightTrack",
           "gun", "turretRotator", "surveyingDevice")
KIND = "abcdefghijklmnopqrstuvwxyz0123456789-"
# BATTLE-ANY rows keep the generated table label (nation-Resource, may hold A-Z/_).
GENERATED_KIND = KIND + "ABCDEFGHIJKLMNOPQRSTUVWXYZ_"
GENERATED_DEVICE_PROFILE = "battle-any"
MAX_PROFILES = 64
MAX_CATALOG_BYTES = 256 * 1024
HEADER = "GENERATED by tools/catalog_build.py from config/catalog/catalog.v1.json; do not edit."


class CatalogBuildError(ValueError):
    """The client sources, profiles or committed outputs violate the contract."""


def require(condition, message):
    if not condition:
        raise CatalogBuildError(message)


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"),
                      ensure_ascii=True, allow_nan=False).encode("ascii")


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def catalog_bytes(document):
    return canonical(document) + b"\n"


def _exact(value, keys):
    return type(value) is dict and set(value) == set(keys)


def load_profiles(path=PROFILES_PATH):
    raw = Path(path).read_bytes()
    require(0 < len(raw) <= 64 * 1024, "server profile file bound")
    value = json.loads(raw)
    require(_exact(value, ("schema", "vehicles")) and value["schema"] == PROFILES_SCHEMA
            and type(value["vehicles"]) is list and 1 <= len(value["vehicles"]) <= MAX_PROFILES,
            "server profile schema")
    seen_kind, seen_vehicle, seen_native = set(), set(), set()
    for p in value["vehicles"]:
        require(_exact(p, ("kind", "vehicle_id", "device_profile", "battle_admission",
                           "legacy_inventory", "client_ui")), "server profile fields")
        alphabet = GENERATED_KIND if p["device_profile"] == GENERATED_DEVICE_PROFILE else KIND
        require(type(p["kind"]) is str and 1 <= len(p["kind"]) <= 32
                and set(p["kind"]) <= set(alphabet) and p["kind"] not in seen_kind, "profile kind")
        require(type(p["vehicle_id"]) is str and p["vehicle_id"].startswith("vehicle:")
                and p["vehicle_id"] not in seen_vehicle, "profile vehicle")
        require(type(p["device_profile"]) is str and 1 <= len(p["device_profile"]) <= 48, "device profile")
        require(p["battle_admission"] in ADMISSION, "battle_admission value")
        legacy = p["legacy_inventory"]
        require(legacy is None or (_exact(legacy, ("native_inventory_id", "suffix"))
                and type(legacy["native_inventory_id"]) is int and 1 <= legacy["native_inventory_id"] <= 2
                and legacy["native_inventory_id"] not in seen_native
                and type(legacy["suffix"]) is str and 1 <= len(legacy["suffix"]) <= 48), "legacy inventory")
        require(_exact(p["client_ui"], ("crew", "ammo"))
                and all(type(v) is bool for v in p["client_ui"].values()), "client UI hints")
        seen_kind.add(p["kind"]); seen_vehicle.add(p["vehicle_id"])
        if legacy is not None:
            seen_native.add(legacy["native_inventory_id"])
    return value, raw


def _tree(read, decode, walk, root, relative, pin, limit=1024 * 1024):
    raw = read(root / relative, min(limit, pin["bytes"]), pin["sha256"])
    require(len(raw) == pin["bytes"], "source size differs: " + relative)
    return dict(walk(decode(raw, max_bytes=limit, max_depth=48, max_nodes=50000)))


def build_document(original_root, profiles_path=PROFILES_PATH):
    """Derive the catalog document; every client fact is re-read from pinned files."""
    from tools.destructible_catalog import no_links, read
    from tools.packed_xml import decode, walk
    from p09e_research_catalog import load_catalog
    from p09e_research_projection import descriptor
    from p09c_ammo_catalog import SOURCE_PINS as SHELL_PINS, XML_PREFIX as USSR_PREFIX
    import p06t_device_source

    profiles, profiles_raw = load_profiles(profiles_path)
    root = no_links(Path(original_root)).resolve(strict=True)
    research = load_catalog(root)
    caps = p06t_device_source.pinned_json(p06t_device_source.CAPS, p06t_device_source.CAPS_SHA256)
    caps_by_profile = {row["profile"]: row for row in caps["profiles"]}
    # v1 shell source pins exist for the USSR tree only (P09C audit); other
    # nations are refused until their shells.xml is pinned.
    shell_sources = {name: {"bytes": SHELL_PINS[USSR_PREFIX + name].size,
                            "sha256": SHELL_PINS[USSR_PREFIX + name].sha256}
                     for name in ("components/guns.xml", "components/shells.xml")}
    trees = {name: _tree(read, decode, walk, root, USSR_PREFIX + name, pin)
             for name, pin in shell_sources.items()}
    vehicles = []
    generated_sha = None
    for p in profiles["vehicles"]:
        v = research.vehicles.get(p["vehicle_id"])
        require(v is not None, "profile vehicle absent from pinned client: " + p["vehicle_id"])
        if p["device_profile"] == GENERATED_DEVICE_PROFILE:
            row, generated_sha = _generated_row(p, v, research, descriptor)
            vehicles.append(row)
            continue
        require(v["nation"] == "ussr", "v1 shell sources are pinned for ussr only: " + p["vehicle_id"])
        require(len(v["turret_positions"]) == 1, "single turret position required: " + p["vehicle_id"])
        d = v["defaults"]
        require(set(d) == set(MODULE_ROLES), "default module roles")
        modules = {role: {"module_id": d[role],
                          "native_compact_id": research.modules[d[role]]["native_compact_id"]}
                   for role in MODULE_ROLES}
        encoded = descriptor(research, {"vehicle_id": p["vehicle_id"], "modules": d})
        gun = research.modules[d["gun"]]["resource_name"]
        turret = research.modules[d["turret"]]["resource_name"]
        gun_params = v["gun_parameters"][d["turret"] + "/" + d["gun"]]
        require(type(gun_params.get("maxAmmo")) is int and 1 <= gun_params["maxAmmo"] <= 1000,
                "stock gun maxAmmo")
        source_vehicle = _tree(read, decode, walk, root, v["source"], research.document["sources"][v["source"]])
        mount = "/turrets0[1]/" + turret + "[1]/guns[1]/" + gun + "[1]"
        require(source_vehicle.get(mount) == "shared"
                and not any(path.startswith(mount + "/shots[") for path in source_vehicle),
                "stock gun must use shared source shots: " + p["vehicle_id"])
        shots_path = "/shared[1]/" + gun + "[1]/shots[1]/"
        shot_names = [path[len(shots_path):-3] for path in trees["components/guns.xml"]
                      if path.startswith(shots_path) and "/" not in path[len(shots_path):]]
        require(1 <= len(shot_names) <= 8, "stock gun shot count")
        shells = []
        for name in shot_names:
            item_id = trees["components/shells.xml"].get("/" + name + "[1]/id[1]")
            family = trees["components/shells.xml"].get("/" + name + "[1]/kind[1]")
            require(type(item_id) is int and 0 < item_id < 4096 and family in FAMILY_SUFFIX,
                    "shell source fields: " + name)
            suffix = FAMILY_SUFFIX[family]
            shells.append({"suffix": suffix, "shell_definition_id": "shell:" + p["kind"] + "-stock-" + suffix,
                           "resource_name": name, "family": family, "item_id": item_id,
                           "native_compact_id": (item_id << 8) + (v["nation_id"] << 4) + 10})
        require(len({s["suffix"] for s in shells}) == len(shells), "duplicate shell family on one gun")
        max_hp = v["hull_max_hp"] + v["turret_max_hp"][d["turret"]]
        cap = caps_by_profile.get(p["device_profile"])
        require(cap is not None and cap["vehicle_max_health"] == max_hp
                and [row["device"] for row in cap["devices"]] == list(DEVICES)
                and [row["roles"] for row in cap["crew"]] == v["crew_roles"],
                "device caps disagree with client source: " + p["kind"])
        if p["battle_admission"] != "none":
            # Every admitted consumer freezes exactly three ordered stacks.
            require(len(shells) == 3, "admitted profile needs three source shell stacks: " + p["kind"])
        classes = [t for t in v["tags"] if t in ("lightTank", "mediumTank", "heavyTank", "AT-SPG", "SPG")]
        require(len(classes) == 1, "vehicle class tag")
        vehicles.append({
            "kind": p["kind"], "vehicle_id": p["vehicle_id"], "resource_name": v["resource_name"],
            "nation": v["nation"], "nation_id": v["nation_id"], "tier": v["tier"], "vehicle_class": classes[0],
            "native_compact_id": v["native_compact_id"], "type_id": v["native_compact_id"] >> 8,
            "modules": modules, "descriptor_hex": encoded.hex(), "descriptor_sha256": sha(encoded),
            "max_hp": max_hp, "ammo_capacity": gun_params["maxAmmo"],
            "crew": [{"seat": i, "roles": list(roles)} for i, roles in enumerate(v["crew_roles"])],
            "shells": shells,
            "devices": [{"device": row["device"], "max_health": row["max_health"],
                         "max_regen_health": row["max_regen_health"]} for row in cap["devices"]],
            "battle_admission": p["battle_admission"], "legacy_inventory": p["legacy_inventory"],
            "client_ui": p["client_ui"]})
    require(len({v["native_compact_id"] for v in vehicles}) == len(vehicles), "duplicate vehicle type")
    # The native client keeps one depot count per shell compact ID, the pool one per
    # mount; a shell shared by two catalog rows would merge two counts (shared depot
    # is a separate decision, owner 2026-10-27).
    shell_ids = [s["native_compact_id"] for v in vehicles for s in v["shells"]]
    require(len(set(shell_ids)) == len(shell_ids), "shell compact ID shared by two catalog rows")
    sources = {"research_catalog_sha256": research.sha256,
               "shell_sources": {USSR_PREFIX + k: v for k, v in shell_sources.items()},
               "device_caps_sha256": p06t_device_source.CAPS_SHA256,
               "server_profiles_sha256": sha(profiles_raw.replace(b"\r\n", b"\n"))}
    if generated_sha is not None:
        sources["battle_profiles_sha256"] = generated_sha
    return {"schema": SCHEMA, "version": 1, "target": TARGET,
            "sources": sources,
            "classification": "VERIFIED_STATIC_PINNED_SOURCE; battle_admission is server policy",
            "vehicles": vehicles}


def _generated_row(p, v, research, descriptor):
    """BATTLE-ANY row: shells, devices and crew come from the SHA-bound generated
    table (its own pinned sources, any nation); every fact the research catalogue
    also carries must agree exactly. Nations whose research-catalogue compact IDs
    differ from the client are refused until their versioned correction."""
    import battle_any
    g = battle_any.profile(p["vehicle_id"])
    require(g is not None and g["status"] == "generated" and g["kind"] == p["kind"],
            "generated battle profile required: " + p["vehicle_id"])
    require(not g["catalog_nation_correction_required"],
            "research catalogue nation differs from client (correction pending): " + p["vehicle_id"])
    identity, gun = g["identity"], g["gun"]
    d = v["defaults"]
    require(set(d) == set(MODULE_ROLES) and identity["modules"] == d, "generated stock modules differ: " + p["kind"])
    modules = {role: {"module_id": d[role], "native_compact_id": research.modules[d[role]]["native_compact_id"]}
               for role in MODULE_ROLES}
    require({role: m["native_compact_id"] for role, m in modules.items()} == identity["module_compact_ids"],
            "generated module compact IDs differ: " + p["kind"])
    encoded = descriptor(research, {"vehicle_id": p["vehicle_id"], "modules": d})
    max_hp = v["hull_max_hp"] + v["turret_max_hp"][d["turret"]]
    gun_params = v["gun_parameters"][d["turret"] + "/" + d["gun"]]
    require(encoded.hex() == identity["descriptor_hex"] and max_hp == identity["max_hp"]
            and v["native_compact_id"] == identity["type_compact_id"] and gun_params.get("maxAmmo") == gun["max_ammo"]
            and [list(r) for r in v["crew_roles"]] == identity["crew_roles"], "generated identity differs: " + p["kind"])
    require(len(g["shots"]) == 3 and len(g["shell_suffixes"]) == 3, "admitted profile needs three shell stacks: " + p["kind"])
    shells = [{"suffix": suffix, "shell_definition_id": "shell:" + p["kind"] + "-stock-" + suffix,
               "resource_name": s["resource"], "family": s["family"], "item_id": s["item_id"],
               "native_compact_id": s["compact_descr"]}
              for suffix, s in zip(g["shell_suffixes"], g["shots"])]
    require(all(s["native_compact_id"] == (s["item_id"] << 8) + (v["nation_id"] << 4) + 10 for s in shells),
            "generated shell compact IDs: " + p["kind"])
    require([row["device"] for row in g["devices"]] == list(DEVICES), "generated device order: " + p["kind"])
    classes = [t for t in v["tags"] if t in ("lightTank", "mediumTank", "heavyTank", "AT-SPG", "SPG")]
    require(classes == [g["vehicle_class"]] and v["tier"] == g["tier"], "vehicle class/tier: " + p["kind"])
    return ({
        "kind": p["kind"], "vehicle_id": p["vehicle_id"], "resource_name": v["resource_name"],
        "nation": v["nation"], "nation_id": v["nation_id"], "tier": v["tier"], "vehicle_class": classes[0],
        "native_compact_id": v["native_compact_id"], "type_id": v["native_compact_id"] >> 8,
        "modules": modules, "descriptor_hex": encoded.hex(), "descriptor_sha256": sha(encoded),
        "max_hp": max_hp, "ammo_capacity": gun["max_ammo"],
        "crew": [{"seat": i, "roles": list(roles)} for i, roles in enumerate(v["crew_roles"])],
        "shells": shells,
        "devices": [{"device": row["device"], "max_health": row["max_health"],
                     "max_regen_health": row["max_regen_health"]} for row in g["devices"]],
        "battle_admission": p["battle_admission"], "legacy_inventory": p["legacy_inventory"],
        "client_ui": p["client_ui"]}, battle_any.data.TABLE_SHA256)


def load_committed(path=CATALOG_PATH):
    raw = Path(path).read_bytes()
    require(0 < len(raw) <= MAX_CATALOG_BYTES, "committed catalog bound")
    document = json.loads(raw)
    require(type(document) is dict and document.get("schema") == SCHEMA and document.get("version") == 1,
            "committed catalog schema")
    require(raw == catalog_bytes(document), "committed catalog must be canonical JSON + LF")
    return document, sha(raw)


