def _py_literal(value, indent=0):
    """Deterministic Python 2.7/3 literal of JSON-shaped data (ASCII only)."""
    pad = "    " * indent
    if isinstance(value, dict):
        if not value:
            return "{}"
        rows = ["%s    %r: %s," % (pad, str(k), _py_literal(value[k], indent + 1)) for k in sorted(value)]
        return "{\n" + "\n".join(rows) + "\n" + pad + "}"
    if isinstance(value, list):
        if not value:
            return "()"
        if all(not isinstance(x, (dict, list)) for x in value):
            return "(" + ", ".join(_py_literal(x) for x in value) + ("," if len(value) == 1 else "") + ")"
        return "(\n" + "\n".join(pad + "    " + _py_literal(x, indent + 1) + "," for x in value) + "\n" + pad + ")"
    if isinstance(value, str):
        require(value.isascii(), "ASCII catalog strings only")
        return repr(str(value))
    require(value is None or type(value) in (bool, int), "catalog scalar type")
    return repr(value)


def render_python(document, digest):
    return ('"""%s\n\nServer-side Python 3 binding. The legacy closed lists stay the default;\n'
            'this data is used only when the worker receives ``--catalog-sha256``.\n"""\n'
            "SCHEMA = %r\nCATALOG_SHA256 = %r\nVEHICLES = %s\n" % (
                HEADER, SCHEMA, digest, _py_literal(document["vehicles"])))


def render_py27(document, digest):
    hints = []
    for v in document["vehicles"]:
        hints.append({"kind": v["kind"], "native_compact_id": v["native_compact_id"], "type_id": v["type_id"],
                      "vehicle_class": v["vehicle_class"], "descriptor_sha256": v["descriptor_sha256"],
                      "max_hp": v["max_hp"], "ammo_capacity": v["ammo_capacity"],
                      "seats": len(v["crew"]), "primary_roles": [c["roles"][0] for c in v["crew"]],
                      "crew_roles": [c["roles"] for c in v["crew"]],
                      "turret_compact_id": v["modules"]["turret"]["native_compact_id"],
                      "gun_compact_id": v["modules"]["gun"]["native_compact_id"],
                      "shell_compact_ids": [s["native_compact_id"] for s in v["shells"]],
                      "battle_admission": v["battle_admission"], "client_ui": v["client_ui"]})
    return ("# -*- coding: utf-8 -*-\n"
            '"""%s\n\nClient UI hints only (Python 2.7.3 in #717). The server stays authoritative;\n'
            "map_drive_client reads this table only when installed with --catalog-v1, the\n"
            "crew/ammunition windows (crew_vehicles) only when installed with --crew-any.\n\"\"\"\n"
            "SCHEMA = %r\nCATALOG_SHA256 = %r\nVEHICLES = %s\n" % (
                HEADER, SCHEMA, digest, _py_literal(hints)))


def render_js(document, digest):
    body = json.dumps(document["vehicles"], sort_keys=True, indent=2, ensure_ascii=True)
    return ("/** %s\n * Bridge binding; used only when the bridge option `catalog` names this hash. */\n"
            "const freeze = v => { if (v && typeof v === 'object') { Object.values(v).forEach(freeze); Object.freeze(v); } return v; };\n"
            "export const CATALOG_SCHEMA = %s;\nexport const CATALOG_SHA256 = %s;\n"
            "export const CATALOG_VEHICLES = freeze(%s);\n" % (
                HEADER, json.dumps(SCHEMA), json.dumps(digest), body))


def _rust_str(value):
    require(value.isascii() and '"' not in value and "\\" not in value, "Rust string literal")
    return '"' + value + '"'


def render_rust(document, digest):
    admission = {"always": "Admission::Always", "zero_economy_policy": "Admission::ZeroEconomyPolicy",
                 "none": "Admission::None"}
    rows = []
    for v in document["vehicles"]:
        descriptor = ",".join("0x%02x" % b for b in bytes.fromhex(v["descriptor_hex"]))
        shells = ",".join("Shell{suffix:%s,shell_definition_id:%s,family:%s,native_compact_id:%d}" % (
            _rust_str(s["suffix"]), _rust_str(s["shell_definition_id"]), _rust_str(s["family"]),
            s["native_compact_id"]) for s in v["shells"])
        devices = ",".join("(%d,%d)" % (d["max_health"], d["max_regen_health"]) for d in v["devices"])
        legacy = v["legacy_inventory"]
        legacy = "None" if legacy is None else "Some((%d,%s))" % (legacy["native_inventory_id"], _rust_str(legacy["suffix"]))
        rows.append(
            "    Vehicle{kind:%s,vehicle_id:%s,native_compact_id:%d,descriptor:&[%s],\n"
            "        max_hp:%d,ammo_capacity:%d,seats:%d,primary_roles:&[%s],gun_compact_id:%d,shells:&[%s],\n"
            "        devices:&[%s],battle_admission:%s,legacy_inventory:%s},"
            % (_rust_str(v["kind"]), _rust_str(v["vehicle_id"]), v["native_compact_id"], descriptor,
               v["max_hp"], v["ammo_capacity"], len(v["crew"]), ",".join(_rust_str(c["roles"][0]) for c in v["crew"]),
               v["modules"]["gun"]["native_compact_id"],
               shells, devices, admission[v["battle_admission"]], legacy))
    return ("//! %s\n"
            "//! Gateway binding. Used only when the gateway config carries\n"
            "//! `\"catalog\":{\"version\":1,\"sha256\":CATALOG_SHA256}`; legacy lists stay the default.\n"
            "pub const CATALOG_SCHEMA:&str=%s;\n"
            "pub const CATALOG_SHA256:&str=%s;\n"
            "pub const CATALOG_JSON:&str=include_str!(\"../../../../config/catalog/catalog.v1.json\");\n"
            "#[derive(Clone,Copy,Debug,PartialEq,Eq)]\n"
            "pub enum Admission{Always,ZeroEconomyPolicy,None}\n"
            "#[derive(Clone,Copy,Debug,PartialEq,Eq)]\n"
            "pub struct Shell{pub suffix:&'static str,pub shell_definition_id:&'static str,pub family:&'static str,pub native_compact_id:u32}\n"
            "#[derive(Clone,Copy,Debug,PartialEq,Eq)]\n"
            "pub struct Vehicle{pub kind:&'static str,pub vehicle_id:&'static str,pub native_compact_id:u32,pub descriptor:&'static [u8],\n"
            "    pub max_hp:u16,pub ammo_capacity:u16,pub seats:usize,pub primary_roles:&'static [&'static str],pub gun_compact_id:u32,pub shells:&'static [Shell],\n"
            "    pub devices:&'static [(u16,u16)],pub battle_admission:Admission,pub legacy_inventory:Option<(u32,&'static str)>}\n"
            "pub const VEHICLES:&[Vehicle]=&[\n%s\n];\n"
            "pub fn by_kind(kind:&str)->Option<&'static Vehicle>{VEHICLES.iter().find(|v|v.kind==kind)}\n"
            "\n#[cfg(test)]\n#[path=\"vehicle_catalog_tests.rs\"]\nmod tests;\n" % (
                HEADER, _rust_str(SCHEMA), _rust_str(digest), "\n".join(rows)))


RENDER = {"rust": render_rust, "python": render_python, "js": render_js, "py27": render_py27}


def render_all(document, digest):
    return {name: RENDER[name](document, digest).encode("ascii") for name in BINDINGS}


def write_outputs(document):
    raw = catalog_bytes(document)
    require(len(raw) <= MAX_CATALOG_BYTES, "catalog size bound")
    CATALOG_PATH.parent.mkdir(parents=True, exist_ok=True)
    CATALOG_PATH.write_bytes(raw)
    digest = sha(raw)
    for name, text in render_all(document, digest).items():
        BINDINGS[name].write_bytes(text)
    return digest


def check_bindings():
    document, digest = load_committed()
    expected = render_all(document, digest)
    stale = [str(BINDINGS[name].relative_to(ROOT)) for name, text in expected.items()
             if not BINDINGS[name].is_file() or BINDINGS[name].read_bytes() != text]
    require(not stale, "stale generated bindings (run build): " + ", ".join(stale))
    return digest, document


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    for name in ("build", "verify-source"):
        sub.add_parser(name).add_argument("--original", required=True, type=Path)
    sub.add_parser("check")
    args = parser.parse_args(argv)
    try:
        if args.command == "check":
            digest, document = check_bindings()
            result = {"status": "PASS", "catalog_sha256": digest, "kinds": [v["kind"] for v in document["vehicles"]]}
        else:
            document = build_document(args.original)
            if args.command == "build":
                digest = write_outputs(document)
            else:
                _, digest = load_committed()
                require(catalog_bytes(document) == CATALOG_PATH.read_bytes(),
                        "committed catalog differs from the pinned client rebuild")
                check_bindings()
            result = {"status": "PASS", "command": args.command, "catalog_sha256": digest,
                      "research_catalog_sha256": document["sources"]["research_catalog_sha256"],
                      "kinds": [v["kind"] for v in document["vehicles"]]}
    except (CatalogBuildError, OSError, KeyError, ValueError) as error:
        parser.exit(1, "CAT-01 catalog rejected: %s\n" % error)
    print(json.dumps(result, sort_keys=True))
    return 0


