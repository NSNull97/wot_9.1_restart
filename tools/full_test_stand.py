"""Prepare one integrated owner test stand from a single checkout.

The 2026-10-19 runs mixed a stand in another worktree (other physics sources,
other Python tools) with a gateway from this checkout, so fixes that passed
here never reached the native battle. This tool copies only the durable state
(SQLite via the backup API, fixtures, identity token) of the latest actual
stand and rebases every resource path onto THIS checkout's local/ root, with
the given gateway executable and freshly built physics. Source stand, its
databases and evidence are never modified. Native acceptance stays NOT_RUN.
"""
import argparse
import hashlib
import json
import shutil
import sqlite3
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOCAL = ROOT / 'local'


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def spellings(path):
    text = str(path)
    return {text, text.replace('\\', '/'), text.replace('/', '\\')}


def rebase(value, mapping):
    """Replace path prefixes (both separators) in every string of a JSON value."""
    if isinstance(value, dict):
        return {key: rebase(item, mapping) for key, item in value.items()}
    if isinstance(value, list):
        return [rebase(item, mapping) for item in value]
    if isinstance(value, str):
        for old, new in mapping:
            for spelling in sorted(spellings(old), key=len, reverse=True):
                if value.lower().startswith(spelling.lower()):
                    rest = value[len(spelling):]
                    sep = '/' if '/' in spelling and '\\' not in spelling else '\\'
                    target = str(new).replace('\\', sep).replace('/', sep)
                    return target + rest.replace('\\', sep).replace('/', sep)
    return value


def pinned_files(value):
    """Yield every {path, sha256} pin of a battle-profiles manifest."""
    if isinstance(value, dict):
        if set(value) == {'path', 'sha256'}:
            yield value
        for item in value.values():
            yield from pinned_files(item)
    elif isinstance(value, list):
        for item in value:
            yield from pinned_files(item)


def physics_manifest(build):
    build = Path(build).resolve(strict=True)
    if not build.is_relative_to(LOCAL / 'build'):
        raise ValueError('physics build must be below this checkout local/build')
    manifest = build / 'artifacts.json'
    if not manifest.exists():
        files = [p for p in sorted((build / 'bin').rglob('*')) if p.is_file()]
        if not (build / 'bin/MapDriveWorker.exe').is_file() or not files:
            raise ValueError('physics build has no MapDriveWorker binaries')
        manifest.write_text(json.dumps(dict(version=1, executable='bin/MapDriveWorker.exe', files=[
            dict(path=p.relative_to(build).as_posix(), bytes=p.stat().st_size, sha256=sha(p)) for p in files]), indent=2) + '\n')
    return manifest


def copy_database(source, target):
    src = sqlite3.connect(f'file:{source.as_posix()}?mode=ro', uri=True)
    dst = sqlite3.connect(target)
    try:
        src.backup(dst)
        checks = {name: dst.execute(f'PRAGMA {name}').fetchone()[0] for name in ('quick_check', 'integrity_check')}
    finally:
        dst.close(); src.close()
    if set(checks.values()) != {'ok'}:
        raise ValueError(f'{target.name} integrity failed: {checks}')
    return checks


