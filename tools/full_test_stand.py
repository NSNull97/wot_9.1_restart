def provision(args):
    """Ready one purchased pool vehicle offline (services stopped).

    Without the CREW-ANY client (prepare --crew-any) the #717 crew/ammunition
    UI patches cover only MS-1/IS-7, so a bought
    T-26/T-34/T-34-85 is readied through the bridge's own store: free research
    path, zero-economy purchase, barracks then free recruits per source seat,
    a 60/20/20 load from the depot, then the same freeze_mixed admission."""
    import sys
    sys.path[:0] = [str(ROOT), str(ROOT / 'tools')]
    from p09e_research_catalog import load_catalog
    from p06t_ammo_loss_store import AmmoLossStore
    from p04m_pool_crew import PINS
    stand = (ROOT / args.stand).resolve(strict=True)
    if not stand.is_relative_to(LOCAL / 'stands') or (stand / 'gateway-process.json').exists():
        raise ValueError('stopped stand below this checkout local/stands required')
    bridge = json.loads((stand / 'bridge.json').read_text(encoding='utf-8'))
    catalog = load_catalog(Path(bridge['ammunition_service']['original_root']))
    account, vehicle_id = args.account, args.vehicle
    store = AmmoLossStore(bridge['game_database'], catalog, account_id=account,
                          shell_catalog=bridge['mixed_service']['shell_catalog'],
                          terminal_policy=bridge['mixed_service']['terminal_policy'])
    steps, counter = [], [0]
    try:
        if not store.zero_economy(account):
            raise ValueError('apply the economy policy first')
        profile = lambda: store.read_profile(account)
        def key(name):
            counter[0] += 1
            return 'stand-provision-' + name + '-' + str(profile()['revision']) + '-' + str(counter[0])
        def research(operation, payload):
            result = store.execute(dict(account_id=account, command_key=key(operation), expected_revision=profile()['revision'],
                                        operation=operation, payload=payload), authenticated_account_id=account)
            steps.append([operation, payload, result['status']])
        def native_request(name, layout):
            return dict(account_id=account, native_database_id=store._project_profile(account, profile())['native_database_id'],
                        command_key=key(name), expected_revision=profile()['revision'], wire_revision=1, layout=layout)
        def unlock(item, depth=0):
            if item in profile()['research']['unlocked']:
                return
            edges = [e for e in catalog.unlocks if e['item_id'] == item]
            if not edges or depth > 40:
                raise ValueError('no bounded research path to ' + item)
            for need in [edges[0]['vehicle_id'], *edges[0]['prerequisite_ids']]:
                unlock(need, depth + 1)
            if item not in profile()['research']['unlocked']:
                research('research', {'vehicle_id': edges[0]['vehicle_id'], 'unlock_index': edges[0]['native_index']})
        kind = store.registry.by_vehicle[vehicle_id].kind
        unlock(vehicle_id)
        if not any(r['vehicle_id'] == vehicle_id for r in profile()['research']['vehicles']):
            research('buy_vehicle', {'vehicle_id': vehicle_id})
        native = next(r for r in profile()['research']['vehicles'] if r['vehicle_id'] == vehicle_id)['native_id']
        for seat, roles in enumerate(PINS[kind][6]):
            members = profile()['crew_inventory']['members']
            if any(m['vehicle_native_id'] == native and m['seat'] == seat for m in members):
                continue
            spare = next((m for m in members if m['vehicle_native_id'] == -1 and m['role'] == roles[0]), None)
            name, layout = ('transfer', [native, seat, spare['native_id']]) if spare else ('recruit', [3, native, seat, 0])
            steps.append([name, layout, getattr(store, name)(native_request(name, layout), authenticated_account_id=account).get('status')])
        mount = store.mounts[store.registry.by_vehicle[vehicle_id].assembly_id]
        counts = [int(mount.capacity * 0.6), int(mount.capacity * 0.2)]
        counts.append(mount.capacity - sum(counts))
        layout = [5, native, 6]
        for shell, n in zip(mount.shell_ids, counts):
            layout += [store.shells[shell].native_compact_id, n]
        layout += [6, 0, 0, 0, 0, 0, 0]
        steps.append(['ammo', layout, store.service(native_request('ammo', layout), authenticated_account_id=account).get('status')])
        frozen = store.freeze_mixed(profile(), native)
        result = dict(account=account, vehicle=vehicle_id, kind=kind, native_inventory_id=native, revision=profile()['revision'],
                      admission=dict(crew=len(frozen['crew_ids']), ammunition=[[a['shell_definition_id'], a['count']] for a in frozen['ammunition']]),
                      steps=steps)
    finally:
        store.close()
    receipt = stand / ('provision-' + account[:8] + '-' + kind + '.json')
    receipt.write_text(json.dumps(result, indent=1, ensure_ascii=False) + chr(10), encoding='utf-8')
    print(json.dumps({k: result[k] for k in ('vehicle', 'native_inventory_id', 'revision', 'admission')}, ensure_ascii=False))


def crew_contract(args):
    """CREW-ANY: move every stand pool owner to crew contract v2 (lifetime 192)
    or back to v1 (only while no identity above 16 was issued).

    Services must be stopped. The stand DB is first copied next to it; each
    account change is one ledger command and one revision (same top store class
    as the bridge worker). Rollback: --version 1, or restore the copy."""
    import sys
    import time
    from contextlib import closing
    sys.path[:0] = [str(ROOT), str(ROOT / 'tools')]
    from p09e_research_catalog import load_catalog
    from p06t_ammo_loss_store import AmmoLossStore
    from p04m_pool_crew import CrewContract, CrewContractV2
    stand = (ROOT / args.stand).resolve(strict=True)
    if not stand.is_relative_to(LOCAL / 'stands') or (stand / 'gateway-process.json').exists():
        raise ValueError('stopped stand below this checkout local/stands required')
    stand_stopped(stand)
    bridge = json.loads((stand / 'bridge.json').read_text(encoding='utf-8'))
    catalog = load_catalog(Path(bridge['ammunition_service']['original_root']))
    target = CrewContractV2 if args.version == 2 else CrewContract
    database = Path(bridge['game_database'])
    backup = stand / ('game.before-crew-v%d-%d.sqlite' % (args.version, int(time.time())))
    with closing(sqlite3.connect(database.resolve().as_uri() + '?mode=ro', uri=True)) as source, closing(sqlite3.connect(backup)) as copy:
        source.backup(copy)
    results = {}
    for account in bridge['mixed_service']['accounts']:
        store = AmmoLossStore(bridge['game_database'], catalog, account_id=account,
                              shell_catalog=bridge['mixed_service']['shell_catalog'],
                              terminal_policy=bridge['mixed_service']['terminal_policy'])
        try:
            profile = store.read_profile(account)
            if store._crew_contract(account) is target:
                results[account] = dict(status='unchanged', crew_schema=target.SCHEMA)
                continue
            native = store._project_profile(account, profile)['native_database_id']
            request = dict(version=args.version, account_id=account, native_database_id=native,
                           command_key='stand-crew-contract-v%d-%d' % (args.version, profile['revision']),
                           expected_revision=profile['revision'], crew_policy_sha256=target.POLICY_SHA256)
            results[account] = store.set_crew_contract(request, authenticated_account_id=account)
        finally:
            store.close()
    receipt = dict(schema='wot091-stand-crew-contract.v1', version=args.version, crew_schema=target.SCHEMA,
                   capacity=target.CAPACITY, backup=str(backup), results=results,
                   rollback='tools/full_test_stand.py crew-contract --stand <stand> --version 1 (identities <= 16) or restore the backup')
    (stand / ('crew-contract-v%d-receipt.json' % args.version)).write_text(json.dumps(receipt, indent=2) + chr(10), encoding='utf-8')
    print(json.dumps(receipt, indent=2))


def stand_stopped(stand):
    for kind in ('gateway', 'bridge'):
        if (stand / (kind + '-process.json')).exists():
            raise ValueError(f'{kind} has a live receipt; stop the stand first')


def battle_map(args):
    """MAPS-01: switch a stopped stand's profile-13 battle to another registry map.

    For every battle kind a new hash-pinned pool is written under the stand:
    the accepted pool's first map entry unchanged plus one entry for the new
    map, whose worker config is the accepted Prohorovka config of that kind
    with only map identity, the package's pinned meshes, the test_lab ctf-base
    spawn and the playable bounds replaced (tools/map_physics_probe.py). Each
    derived config is settled and driven once on the stand's own physics
    build. The previous battle-profiles.json is kept for rollback. Accepted
    pools, configs and catalogs are never modified.
    """
    import sys
    sys.path.insert(0, str(ROOT / 'tools'))
    import map_package as mp
    import map_physics_probe as probe
    # The local root that holds this checkout's stands (equals local/ unless
    # local/stands is a junction into another checkout's local/).
    local = (LOCAL / 'stands').resolve(strict=True).parent
    stand = Path(args.stand).resolve(strict=True)
    if not stand.is_relative_to(local / 'stands'):
        raise ValueError('stand must be below this checkout local/stands')
    stand_stopped(stand)
    package_dir = Path(args.package).resolve(strict=True)
    package, package_sha = mp.verify(package_dir)
    name = package['map']
    target = stand / ('map-' + name)
    if target.exists():
        raise ValueError(f'{target} already exists')
    catalog = Path(args.catalog).resolve(strict=True)
    if not catalog.is_relative_to(local) or not package_dir.is_relative_to(local):
        raise ValueError('package and catalog must be below this checkout local/')
    catalog_value = json.loads(catalog.read_text(encoding='utf-8'))
    if catalog_value.get('map') != name or catalog_value.get('version') != 7:
        raise ValueError('catalog must be a v7 catalog of the same map')
    profiles_path = stand / 'battle-profiles.json'
    profiles = json.loads(profiles_path.read_text(encoding='utf-8'))
    if profiles.get('map') == name:
        raise ValueError('stand already battles on this map')
    physics_build = Path(profiles['shared_physics']['path']).resolve(strict=True).parent
    dll = (physics_build / 'bin/MapDriveWorker.dll').read_bytes()
    if f'"asset": "{name}"'.encode() not in dll:
        raise ValueError('stand physics build does not embed this map in its registry; rebuild physics from this checkout')
    executable = physics_build / 'bin/MapDriveWorker.exe'
    arena = json.loads((package_dir / 'arena.json').read_text(encoding='utf-8'))
    target.mkdir()
    receipt = dict(schema='wot091-stand-battle-map.v1', map=name, package=str(package_dir), package_sha256=package_sha,
                   catalog=dict(path=str(catalog), sha256=sha(catalog)), physics_build=str(physics_build),
                   previous_battle_profiles_sha256=sha(profiles_path), spawn_policy=probe.SPAWN_POLICY, kinds={},
                   native='NOT_RUN')
    for profile in profiles['profiles']:
        kind = profile['kind']
        pool_path = Path(profile['pool']['path'])
        if sha(pool_path) != profile['pool']['sha256']:
            raise ValueError(f'{kind} pool pin differs')
        pool = json.loads(pool_path.read_text(encoding='utf-8'))
        source = [m for m in pool['maps'] if m['asset'] == profiles['map']]
        if len(pool['maps']) != 2 or len(source) != 1:
            raise ValueError(f'{kind} pool must hold two maps including the current battle map')
        template_path = Path(source[0]['config'])
        if sha(template_path) != source[0]['config_sha256']:
            raise ValueError(f'{kind} template config pin differs')
        config, _ = probe.derived_config(json.loads(template_path.read_text(encoding='utf-8')), package, package_dir,
                                         arena, args.team, local)
        config_raw = json.dumps(config, separators=(',', ':'), sort_keys=True).encode('ascii')
        config_path = target / f'{name}-{kind}-config.json'
        config_path.write_bytes(config_raw)
        keep = [m for m in pool['maps'] if m['asset'] != profiles['map']][0]
        pool['maps'] = [keep, dict(arena_type_id=package['arena_type_id'], asset=name, config=str(config_path),
                                   config_sha256=hashlib.sha256(config_raw).hexdigest())]
        new_pool = target / f'pool-{kind}.json'
        new_pool.write_text(json.dumps(pool, indent=1) + '\n', encoding='utf-8')
        ready, states, _, code, _ = probe.run_worker(executable, local, config_path, hashlib.sha256(config_raw).hexdigest(), 80)
        result = probe.check(ready, states, probe.Ground(package_dir))
        if result['status'] != 'PASS' or code != 0:
            raise ValueError(f'{kind} derived config failed the physics probe: {result["problems"]}')
        profile['pool'] = dict(path=str(new_pool), sha256=sha(new_pool))
        receipt['kinds'][kind] = dict(template=str(template_path), template_sha256=source[0]['config_sha256'],
                                      config_sha256=hashlib.sha256(config_raw).hexdigest(), pool_sha256=profile['pool']['sha256'],
                                      probe=dict(driven_m=result['driven_m'], min_clearance_m=result['min_clearance_m'],
                                                 max_clearance_m=result['max_clearance_m'], contacts=result['ready']['contacts']))
    profiles['map'] = name
    profiles['catalog'] = dict(path=str(catalog), sha256=sha(catalog))
    backup = stand / f'battle-profiles.before-{name}.json'
    shutil.copy2(profiles_path, backup)
    profiles_path.write_text(json.dumps(profiles, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
    receipt.update(battle_profiles_sha256=sha(profiles_path), rollback=f'copy {backup.name} over battle-profiles.json')
    (target / 'receipt.json').write_text(json.dumps(receipt, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(receipt, indent=2))


