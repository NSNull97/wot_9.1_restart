"""Prepare one integrated owner test stand from a single checkout.

The 2026-10-19 runs mixed a stand in another worktree (other physics sources,
other Python tools) with a gateway from this checkout, so fixes that passed
here never reached the native battle. This tool copies only the durable state
(SQLite via the backup API, fixtures, identity token) of the latest actual
stand and rebases every resource path onto THIS checkout's local/ root, with
the given gateway executable and freshly built physics. Source stand, its
databases and evidence are never modified. Native acceptance stays NOT_RUN.
"""
import argparse
import hashlib
import json
import shutil
import sqlite3
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOCAL = ROOT / 'local'


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def spellings(path):
    text = str(path)
    return {text, text.replace('\\', '/'), text.replace('/', '\\')}


def rebase(value, mapping):
    """Replace path prefixes (both separators) in every string of a JSON value."""
    if isinstance(value, dict):
        return {key: rebase(item, mapping) for key, item in value.items()}
    if isinstance(value, list):
        return [rebase(item, mapping) for item in value]
    if isinstance(value, str):
        for old, new in mapping:
            for spelling in sorted(spellings(old), key=len, reverse=True):
                if value.lower().startswith(spelling.lower()):
                    rest = value[len(spelling):]
                    sep = '/' if '/' in spelling and '\\' not in spelling else '\\'
                    target = str(new).replace('\\', sep).replace('/', sep)
                    return target + rest.replace('\\', sep).replace('/', sep)
    return value


def pinned_files(value):
    """Yield every {path, sha256} pin of a battle-profiles manifest."""
    if isinstance(value, dict):
        if set(value) == {'path', 'sha256'}:
            yield value
        for item in value.values():
            yield from pinned_files(item)
    elif isinstance(value, list):
        for item in value:
            yield from pinned_files(item)


def physics_manifest(build):
    build = Path(build).resolve(strict=True)
    if not build.is_relative_to(LOCAL / 'build'):
        raise ValueError('physics build must be below this checkout local/build')
    manifest = build / 'artifacts.json'
    if not manifest.exists():
        files = [p for p in sorted((build / 'bin').rglob('*')) if p.is_file()]
        if not (build / 'bin/MapDriveWorker.exe').is_file() or not files:
            raise ValueError('physics build has no MapDriveWorker binaries')
        manifest.write_text(json.dumps(dict(version=1, executable='bin/MapDriveWorker.exe', files=[
            dict(path=p.relative_to(build).as_posix(), bytes=p.stat().st_size, sha256=sha(p)) for p in files]), indent=2) + '\n')
    return manifest


def copy_database(source, target):
    src = sqlite3.connect(f'file:{source.as_posix()}?mode=ro', uri=True)
    dst = sqlite3.connect(target)
    try:
        src.backup(dst)
        checks = {name: dst.execute(f'PRAGMA {name}').fetchone()[0] for name in ('quick_check', 'integrity_check')}
    finally:
        dst.close(); src.close()
    if set(checks.values()) != {'ok'}:
        raise ValueError(f'{target.name} integrity failed: {checks}')
    return checks


SERVICES = r'''param([ValidateSet('start','stop')][string]$Action)
# Generated by tools/full_test_stand.py. Bridge, Python tools, gateway and
# physics all come from __ROOT__.
$ErrorActionPreference = 'Stop'
$root = '__ROOT__'
$stand = '__STAND__'
$gatewayExe = '__GATEWAY__'
$order = if ($Action -eq 'start') { @('bridge','gateway') } else { @('gateway','bridge') }
foreach ($kind in $order) {
  $record = Join-Path $stand ($kind + '-process.json')
  if ($Action -eq 'stop') {
    if (-not (Test-Path $record)) { Write-Output "$kind not started"; continue }
    $r = Get-Content $record -Raw | ConvertFrom-Json
    $p = Get-CimInstance Win32_Process -Filter ("ProcessId=" + $r.pid)
    if ($p -and $p.ExecutablePath -eq $r.exe -and $p.CommandLine.Contains($r.config)) { Stop-Process -Id $r.pid; Wait-Process -Id $r.pid -Timeout 10 -ErrorAction SilentlyContinue; Write-Output "$kind stopped: $($r.pid)" }
    else { Write-Output "$kind already absent or not ours: $($r.pid)" }
    Rename-Item $record ($kind + '-process-' + (Get-Date -Format 'HHmmss') + '.json')
    continue
  }
  if (Test-Path $record) { throw "$kind already has a live receipt" }
  $stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
  if ($kind -eq 'bridge') {
    $config = Join-Path $stand 'bridge.json'
    $exe = (Get-Command node).Source; $args = @('server/identity/service.mjs','--config',$config)
  } else {
    $config = Join-Path $stand 'gateway.json'
    $exe = $gatewayExe
    $env:WOT091_STAB_DIAGNOSTICS_DIR = Join-Path $stand ('cadence-' + $stamp)
    New-Item -ItemType Directory -Force $env:WOT091_STAB_DIAGNOSTICS_DIR | Out-Null
    $args = @('legacy091-profile13',(Join-Path $root 'local\server\native-private.pem'),(Join-Path $root 'local\server\client-digest.bin'),
      $config,(Join-Path $stand 'battle-profiles.json'),(Join-Path $stand ('capture-' + $stamp)))
  }
  $out = Join-Path $stand ($kind + '-' + $stamp + '.stdout.log'); $err = Join-Path $stand ($kind + '-' + $stamp + '.stderr.log')
  $p = Start-Process -FilePath $exe -ArgumentList $args -WorkingDirectory $root -RedirectStandardOutput $out -RedirectStandardError $err -WindowStyle Hidden -PassThru
  @{pid=$p.Id;kind=$kind;exe=$exe;exe_sha256=(Get-FileHash $exe -Algorithm SHA256).Hash.ToLower();config=$config;stdout=$out;stderr=$err;started_utc=[DateTime]::UtcNow.ToString('o')} | ConvertTo-Json | Set-Content $record -Encoding utf8
  Start-Sleep -Seconds 5; $p.Refresh()
  if ($p.HasExited) { Get-Content $err; throw "$kind exited at startup" }
  Write-Output "$kind started: $($p.Id)"; Get-Content $out | Select-Object -Last 3
}
'''


def prepare(args):
    source = Path(args.source_stand).resolve(strict=True)
    out = (ROOT / args.out).resolve()
    if not out.is_relative_to(LOCAL / 'stands') or out.exists():
        raise ValueError('fresh output under this checkout local/stands required')
    gateway = Path(args.gateway).resolve(strict=True)
    if not gateway.is_relative_to(LOCAL / 'build') and not gateway.is_relative_to(Path(args.allow_gateway_root).resolve() if args.allow_gateway_root else gateway.parent / '__none__'):
        raise ValueError('gateway executable must come from a recorded build of this checkout')
    configs = {name: json.loads((source / name).read_text(encoding='utf-8')) for name in ('bridge.json', 'gateway.json', 'battle-profiles.json')}
    source_local = Path(configs['gateway.json']['local_root'])
    mapping = [(source, out), (source_local, LOCAL)]
    out.mkdir(parents=True)
    receipt = dict(schema='wot091-full-test-stand.v1', created_utc=datetime.now(timezone.utc).isoformat(),
                   checkout=str(ROOT), source_stand=str(source), source_local=str(source_local),
                   native='NOT_RUN', databases={})
    for name in ('game.sqlite', 'web.sqlite'):
        checks = copy_database(source / name, out / name)
        receipt['databases'][name] = dict(checks, sha256=sha(out / name))
    shutil.copytree(source / 'fixtures', out / 'fixtures')
    shutil.copy2(source / 'identity.token', out / 'identity.token')
    rebased = {name: rebase(value, mapping) for name, value in configs.items()}
    profiles = rebased['battle-profiles.json']
    manifest = physics_manifest(args.physics)
    profiles['shared_physics'] = dict(path=str(manifest), sha256=sha(manifest))
    for pin in pinned_files(profiles):
        path = Path(pin['path'])
        if not path.is_file() or not path.resolve().is_relative_to(LOCAL):
            raise ValueError(f'missing or foreign pinned resource: {path}')
        pin['sha256'] = sha(path)
    for name, value in rebased.items():
        text = json.dumps(value, indent=2, ensure_ascii=False)
        for old, _ in mapping:
            if any(spelling.lower() in text.replace('\\\\', '\\').lower() for spelling in spellings(old)):
                raise ValueError(f'{name} still references {old}')
        (out / name).write_text(text + '\n', encoding='utf-8')
    services = SERVICES.replace('__ROOT__', str(ROOT)).replace('__STAND__', str(out)).replace('__GATEWAY__', str(gateway))
    (out / 'services.ps1').write_text(services, encoding='utf-8')
    receipt.update(gateway=dict(path=str(gateway), sha256=sha(gateway)),
                   physics=dict(manifest=str(manifest), sha256=sha(manifest),
                                dll_sha256=sha(manifest.parent / 'bin/MapDriveWorker.dll')),
                   ports=dict(login=rebased['gateway.json']['login_bind'], base=rebased['gateway.json']['base_bind'],
                              identity=rebased['bridge.json']['port']))
    (out / 'stand-receipt.json').write_text(json.dumps(receipt, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(receipt, indent=2))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=('prepare',))
    parser.add_argument('--source-stand', required=True, help='latest actual stand directory (read-only)')
    parser.add_argument('--physics', required=True, help='physics build dir below local/build')
    parser.add_argument('--gateway', required=True, help='sr-gateway.exe from a recorded build')
    parser.add_argument('--allow-gateway-root', help='additional recorded build root (build.py --cargo-temp-target)')
    parser.add_argument('--out', required=True, help='fresh stand dir below local/stands')
    prepare(parser.parse_args())


if __name__ == '__main__':
    main()
